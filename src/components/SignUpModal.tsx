import React, { useState, useEffect } from 'react';
import { submitLead } from '../supabaseClient';
import './SignUpModal.css';

export const SignUpModal: React.FC = () => {
  const [isOpen, setIsOpen] = useState(window.location.hash === '#signup');
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [businessName, setBusinessName] = useState('');
  const [businessType, setBusinessType] = useState('restaurante');
  const [notes, setNotes] = useState('');
  
  const [loading, setLoading] = useState(false);
  const [status, setStatus] = useState<'idle' | 'success' | 'error'>('idle');
  const [errorMsg, setErrorMsg] = useState('');

  useEffect(() => {
    const handleHash = () => {
      const open = window.location.hash === '#signup';
      setIsOpen(open);
      if (!open) {
        // Reset status when closing
        setStatus('idle');
        setErrorMsg('');
        document.body.style.overflow = '';
      } else {
        document.body.style.overflow = 'hidden';
      }
    };
    
    if (window.location.hash === '#signup') {
      document.body.style.overflow = 'hidden';
    }

    window.addEventListener('hashchange', handleHash);
    return () => {
      window.removeEventListener('hashchange', handleHash);
      document.body.style.overflow = '';
    };
  }, []);

  const handleClose = () => {
    // Changing the hash will trigger the event listener and close the modal
    window.location.hash = '#';
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setLoading(true);
    setStatus('idle');
    setErrorMsg('');

    // 1. Guardar en Supabase (disparará el Trigger en la DB para enviar el correo)
    const result = await submitLead({
      name,
      email,
      business_name: businessName,
      business_type: businessType,
      notes
    });

    if (result.success) {
      setStatus('success');
      // Clear form
      setName('');
      setEmail('');
      setBusinessName('');
      setBusinessType('restaurante');
      setNotes('');
    } else {
      setStatus('error');
      setErrorMsg(result.error || 'Ocurrió un error inesperado.');
    }
    setLoading(false);
  };

  if (!isOpen) return null;

  const isTableMissing = errorMsg.toLowerCase().includes('relation') || errorMsg.toLowerCase().includes('not found') || errorMsg.toLowerCase().includes('404');

  return (
    <div className="modal-overlay" onClick={handleClose}>
      <div className="modal-card" onClick={(e) => e.stopPropagation()}>
        
        {/* Header */}
        <div className="modal-header">
          <h3 className="modal-title">Comenzar con PideloSeguro.mx</h3>
          <button className="modal-close-btn" onClick={handleClose} aria-label="Cerrar modal">
            <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
              <line x1="18" y1="6" x2="6" y2="18"></line>
              <line x1="6" y1="6" x2="18" y2="18"></line>
            </svg>
          </button>
        </div>

        {/* Body */}
        <div className="modal-body">
          {status === 'success' ? (
            <div style={{ display: 'flex', flexDirection: 'column', gap: '16px', textAlign: 'center', padding: '20px 0' }}>
              <div style={{ fontSize: '48px', color: '#E53E3E' }}>✓</div>
              <h4 style={{ fontSize: '18px', fontWeight: '600', color: '#2d3748', margin: '0 0 8px 0' }}>
                ¡Registro Exitoso!
              </h4>
              <p style={{ fontSize: '14px', color: '#718096', margin: 0, lineHeight: '1.5' }}>
                Se envió la solicitud de registro con éxito. Nos pondremos en contacto contigo muy pronto para configurar tu menú y repartidores.
              </p>
            </div>
          ) : (
            <form onSubmit={handleSubmit} style={{ display: 'flex', flexDirection: 'column', gap: '16px' }}>
              
              {status === 'error' && (
                <div className="modal-alert modal-alert-error">
                  <strong>Error al guardar:</strong> {errorMsg}
                  
                  {isTableMissing && (
                    <div>
                      <br />
                      Parece que la tabla <code>leads</code> no existe en tu proyecto de Supabase. Puedes crearla ejecutando el siguiente código SQL en tu editor de Supabase:
                      <pre className="sql-instruction">
{`create table public.leads (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text,
  email text,
  business_name text,
  business_type text,
  notes text
);`}
                      </pre>
                    </div>
                  )}
                </div>
              )}

              {/* Sección 1: Datos de Contacto */}
              <div className="modal-section-title">
                <span className="modal-section-number">1</span>
                <h4>Tus Datos de Contacto</h4>
              </div>

              <div className="modal-form-group">
                <label className="modal-label" htmlFor="lead-name">Nombre Completo</label>
                <input 
                  type="text" 
                  id="lead-name"
                  className="modal-input"
                  required
                  placeholder="Ej. Juan Pérez"
                  value={name}
                  onChange={(e) => setName(e.target.value)}
                />
              </div>

              <div className="modal-form-group">
                <label className="modal-label" htmlFor="lead-email">Correo Electrónico</label>
                <input 
                  type="email" 
                  id="lead-email"
                  className="modal-input"
                  required
                  placeholder="Ej. juan@minegocio.com"
                  value={email}
                  onChange={(e) => setEmail(e.target.value)}
                />
              </div>

              {/* Separador y Sección 2: Datos de la Empresa */}
              <div className="modal-section-divider"></div>

              <div className="modal-section-title">
                <span className="modal-section-number">2</span>
                <h4>Datos de tu Negocio / Empresa</h4>
              </div>

              <div className="modal-form-group">
                <label className="modal-label" htmlFor="lead-business">Nombre del Negocio / Empresa</label>
                <input 
                  type="text" 
                  id="lead-business"
                  className="modal-input"
                  required
                  placeholder="Ej. Tortas La Purísima"
                  value={businessName}
                  onChange={(e) => setBusinessName(e.target.value)}
                />
              </div>

              <div className="modal-form-group">
                <label className="modal-label" htmlFor="lead-type">Tipo de Negocio</label>
                <select 
                  id="lead-type"
                  className="modal-select"
                  value={businessType}
                  onChange={(e) => setBusinessType(e.target.value)}
                >
                  <option value="restaurante">Restaurante</option>
                  <option value="comida_rapida">Comida Rápida</option>
                  <option value="ecommerce">E-commerce</option>
                  <option value="tienda_fisica">Tienda Física</option>
                  <option value="oficina">Oficina / Corporativo</option>
                  <option value="otro">Otro</option>
                </select>
              </div>

              <div className="modal-form-group">
                <label className="modal-label" htmlFor="lead-notes">Mensaje / Notas adicionales</label>
                <textarea 
                  id="lead-notes"
                  className="modal-textarea"
                  placeholder="Ej. Tengo 3 repartidores en moto y entrego a 5km a la redonda..."
                  value={notes}
                  onChange={(e) => setNotes(e.target.value)}
                />
              </div>

              <button 
                type="submit" 
                className="modal-submit-btn"
                disabled={loading}
              >
                {loading ? 'Enviando...' : 'Enviar Datos'}
              </button>

            </form>
          )}
        </div>

      </div>
    </div>
  );
};
